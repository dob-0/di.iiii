#!/usr/bin/env node
/**
 * chart-lists.mjs — turn the maker charts of the Platina rental lamps (scripts/place/fixtures/charts/<id>.json) into the
 * roles module src/rigbuild/platinaChannelLists.js that fixtureTypes.js reads (MAKER_CHANNEL_LISTS).
 *
 *   node scripts/rigbuild/chart-lists.mjs            # write
 *   node scripts/rigbuild/chart-lists.mjs --check    # exit 1 when the committed module is stale
 *
 * A chart whose modes carry `channels: null` (the K15's, OWED) yields no list: nothing is invented.
 * The charts come from scripts/place/fixtures/import_platina_manuals.py; the module is generated, never edited by hand.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
export const CHART_IDS = ['cp-aleda-beye-k10', 'cp-hy-beye-k15', 'acme-pixel-line-ip', 'acme-xp16r-bsw', 'magmatic-magma-prime']
export const MODULE_FILE = 'src/rigbuild/platinaChannelLists.js'

export const moduleText = ({ charts = CHART_IDS } = {}) => {
    const lists = {}
    for (const id of charts) {
        const chart = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts/place/fixtures/charts', `${id}.json`), 'utf8'))
        const modes = {}
        for (const [footprint, mode] of Object.entries(chart.modes)) {
            if (!mode.channels) continue
            modes[footprint] = mode.channels.map((c) => ({
                role: c.role,
                label: c.text && !/^(p\d\d[rgbw]|cw\d\d)$/.test(c.role) ? `${c.function} (${c.text.replace(/^p\d+(?:-\d+)?:\s*/, '')})` : c.function,
                ...(c.default !== undefined ? { default: c.default } : {}),
                ...(c.cap ? { cap: c.cap } : {})
            }))
        }
        if (!Object.keys(modes).length) continue
        lists[chart.code] = {
            fixture: `${chart.maker} ${chart.model} (${chart.manual.url})`,
            basis: 'EXACT',
            url: chart.manual.url,
            licence: null,
            modes
        }
    }
    return `// GENERATED by scripts/rigbuild/chart-lists.mjs from scripts/place/fixtures/charts/*.json — never edit by hand.\n// The Platina rental lamps' channel lists as the makers' manuals print them (read 2026-11-11). A list the maker's chart did not give (the K15's) is absent.\nexport const PLATINA_CHANNEL_LISTS = ${JSON.stringify(lists, null, 4)}\n`
}

const main = () => {
    const text = moduleText()
    const file = path.join(ROOT, MODULE_FILE)
    if (process.argv.includes('--check')) {
        if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) { console.error(`stale: ${MODULE_FILE} — run: node scripts/rigbuild/chart-lists.mjs`); process.exit(1) }
        console.log(`${MODULE_FILE} is current`)
        return
    }
    fs.writeFileSync(file, text)
    console.log(`wrote ${MODULE_FILE}`)
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
