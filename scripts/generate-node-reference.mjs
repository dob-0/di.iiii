#!/usr/bin/env node
/**
 * generate-node-reference.mjs — the AI-readable node reference.
 *
 * Generated, never hand-edited, from two sources of truth: the registry
 * (src/project/nodeRegistry.js — every type's real ports, defaults, bounds)
 * and the per-node examples (src/project/graph/examples/nodes/ — one worked,
 * tested graph per type, docs/ai/audits/2026-09-14-raw-fix-plan.md item 6).
 * Writes docs/nodes/README.md (an index by family) and one docs/nodes/
 * <family>.md per family. `npm run docs:nodes` regenerates both;
 * `npm run docs:nodes:check` (scripts/check-node-reference.mjs) fails if the
 * checked-in files have drifted from what this script would produce —
 * the same shape as docs:ai:sync / docs:ai:check.
 *
 * Exports the pure content-builders so the checker can import them without
 * writing anything.
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

import { getNodeOperations, getNodeType } from '../src/project/nodeRegistry.js'
import { NODE_EXAMPLE_FAMILIES } from '../src/project/graph/examples/nodes/index.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
export const repoRoot = path.resolve(__dirname, '..')

export const DOCS_DIR = 'docs/nodes'
export const README_PATH = `${DOCS_DIR}/README.md`
export const familyFilePath = (familyId) => `${DOCS_DIR}/${familyId}.md`

const formatValue = (value) => JSON.stringify(value)

const portLine = (port) => {
    const bits = [`\`${port.id}\``, `(${port.type})`]
    if (port.label) bits.push(`—`, port.label)
    const extra = []
    if (port.default !== undefined) extra.push(`default ${formatValue(port.default)}`)
    if (port.min !== undefined) extra.push(`min ${port.min}`)
    if (port.max !== undefined) extra.push(`max ${port.max}`)
    if (port.step !== undefined) extra.push(`step ${port.step}`)
    if (Array.isArray(port.options)) extra.push(`options: ${port.options.map((o) => o.label ?? String(o.value)).join(', ')}`)
    return `- ${bits.join(' ')}${extra.length ? ` — ${extra.join(', ')}` : ''}`
}

const portsBlock = (title, ports) => {
    if (!ports || !ports.length) return `**${title}:** none`
    return `**${title}:**\n${ports.map(portLine).join('\n')}`
}

const operationsBlock = (typeId) => {
    const operations = getNodeOperations(typeId)
    if (!operations) return ''
    const rows = operations.map((op) => {
        const ports = op.inputs.map((p) => `\`${p.id}\` ${p.label}${p.unused ? ' (unused in this operation)' : ''}`).join(', ')
        return `| ${op.label} (\`${op.value}\`) | ${ports} |`
    })
    return [
        '',
        '**Operations** — one card, a menu; the ports below are static, only the label/default per operation changes:',
        '',
        '| Operation | Ports |',
        '| --- | --- |',
        ...rows
    ].join('\n')
}

// Strips the always-null bookkeeping fields (runtimeId, createdBy) so the
// copyable JSON is only what an author actually set.
const compactNode = (node) => {
    const out = {
        id: node.id,
        typeId: node.typeId,
        label: node.label,
        graphX: node.graphX,
        graphY: node.graphY,
        values: node.values
    }
    if (node.parentId) out.parentId = node.parentId
    return out
}

const compactEdge = (edge) => ({
    id: edge.id,
    fromNodeId: edge.fromNodeId,
    fromPort: edge.fromPort,
    toNodeId: edge.toNodeId,
    toPort: edge.toPort
})

const exampleGraphJson = (example) => {
    const { nodes, edges } = example.build()
    return JSON.stringify({ nodes: nodes.map(compactNode), edges: edges.map(compactEdge) }, null, 2)
}

const nodeSection = (example) => {
    const type = getNodeType(example.typeId)
    const lines = [
        `## ${type?.label || example.title} (\`${example.typeId}\`)`,
        '',
        example.story,
        '',
        portsBlock('Inputs', type?.inputs),
        '',
        portsBlock('Outputs', type?.outputs)
    ]
    const operations = operationsBlock(example.typeId)
    if (operations) lines.push(operations)
    lines.push(
        '',
        '**Example graph** — build this exact document (createNode/createEdge, src/project/nodeRegistry.js) to get a working demo of this node; ids are stable so re-running the source is idempotent:',
        '',
        '```json',
        exampleGraphJson(example),
        '```'
    )
    return lines.join('\n')
}

export const buildFamilyDoc = (family) => {
    const header = [
        `# ${family.label} — node reference`,
        '',
        'Generated by `scripts/generate-node-reference.mjs` from the registry and',
        '`src/project/graph/examples/nodes/`. Do not hand-edit; `npm run docs:nodes` regenerates',
        'this file, and `npm run docs:nodes:check` fails CI if it has drifted.',
        '',
        `[← index](README.md)`,
        ''
    ]
    const sections = family.examples.map(nodeSection)
    return `${header.join('\n')}\n${sections.join('\n\n')}\n`
}

export const buildReadme = () => {
    const lines = [
        '# Node reference',
        '',
        'Every node type the palette can place, one entry per family, generated from',
        '`src/project/nodeRegistry.js` and `src/project/graph/examples/nodes/` by',
        '`scripts/generate-node-reference.mjs` (`npm run docs:nodes`; `npm run docs:nodes:check`',
        'fails CI if this drifts from the source). Written for an AI (or a person) building a',
        'graph: each node\'s real ports, and a small working example graph as JSON to copy.',
        '',
        'For the full audit this was built from — what is real vs. partial, and every cross-cutting',
        'defect — see `docs/ai/audits/2026-09-14-raw-nodes.md`.',
        '',
        '## Families',
        ''
    ]
    for (const family of NODE_EXAMPLE_FAMILIES) {
        lines.push(`### ${family.label}`, '', `See [${family.id}.md](${family.id}.md) for full ports and each example graph.`, '')
        for (const example of family.examples) {
            const type = getNodeType(example.typeId)
            lines.push(`- **${type?.label || example.title}** (\`${example.typeId}\`) — ${example.story}`)
        }
        lines.push('')
    }
    lines.push(
        '## Putting examples into a real di.iiii',
        '',
        '`scripts/push-node-examples.mjs --base <url> --space <id> [--token <token>] [--family <id>]',
        '[--dry-run]` creates one project per family (e.g. "examples · numbers", slug',
        '`examples-numbers`) inside the given space, using the same APIs the app itself uses:',
        '`POST /api/spaces/:space/projects` to create the project (a second run finds the same slug',
        'already there and reuses it — it does NOT fail), then `POST /api/projects/:project/ops`',
        'with `createNode`/`createEdge` ops whose `opId` is the node/edge\'s own stable id, so',
        'resubmitting the SAME example is a no-op (serverXR drops an op whose `opId` it already',
        'applied). Known limit: it only ever creates — if an example\'s `build()` changes after a',
        'first push, re-running does not update the nodes already there; delete the family\'s',
        'project first for a clean re-push. Pass `--token` for a space that requires authentication,',
        '`--family <id>` to push just one family, `--dry-run` to print the op counts and touch',
        'nothing. This script is NEVER run against a live install from an agent session — only the',
        'lead runs it, against a real space, after review.',
        '',
        '```sh',
        'node scripts/push-node-examples.mjs --base https://staging.di-studio.xyz --space my-space --token "$TOKEN"',
        '```'
    )
    return `${lines.join('\n')}\n`
}

export const buildAll = () => {
    const files = new Map()
    files.set(README_PATH, buildReadme())
    for (const family of NODE_EXAMPLE_FAMILIES) {
        files.set(familyFilePath(family.id), buildFamilyDoc(family))
    }
    return files
}

const main = async () => {
    const files = buildAll()
    await fs.mkdir(path.join(repoRoot, DOCS_DIR), { recursive: true })
    for (const [relativePath, content] of files) {
        await fs.writeFile(path.join(repoRoot, relativePath), content, 'utf8')
    }
    console.log(`docs:nodes wrote ${files.size} files under ${DOCS_DIR}/`)
}

if (import.meta.url === `file://${process.argv[1]}`) {
    await main()
}
