#!/usr/bin/env node
// Writes src/project/nodes/laser.text/hersheyRomanSimplex.js from a Hershey .jhf file (laser Phase 9).
//
// Source used on 2026-10-20: rowmans.jhf (Roman Simplex) inside the npm package `hershey` 2.1.7
// (https://registry.npmjs.org/hershey/-/hershey-2.1.7.tgz, font/jhf/rowmans.jhf, sha256
// 8718fb129c0f6bce89c84fe41bc467e39534d215a6f7c3220cc5789a8a7d8618), which carries the original Usenet
// distribution's notice as HERSHEY-LICENSE. The .jhf layout (Kamal Mostafa's conversion of Jim Hurt's
// packed data): columns 0-4 the Hershey glyph number, 5-7 the vertex count (the bounds pair included),
// then pairs of characters, each coordinate = its code - 'R'; the first pair is the left and right
// bounds; " R" lifts the pen. Line k (0-based) is ASCII 32 + k. Only ASCII 32-126 are kept.
//
// Run: node scripts/laser/hershey-to-module.mjs <rowmans.jhf>   (refuses a file that does not check out)
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const src = process.argv[2]
if (!src) { console.error('usage: hershey-to-module.mjs <rowmans.jhf>'); process.exit(2) }
const raw = fs.readFileSync(src)
const sha = crypto.createHash('sha256').update(raw).digest('hex')
const lines = raw.toString('latin1').split(/\r?\n/).filter((l) => l.trim().length)
const FIRST = 32
const LAST = 126
const glyphs = []
for (let code = FIRST; code <= LAST; code += 1) {
    const line = lines[code - FIRST]
    if (!line) { console.error(`no line for ASCII ${code}`); process.exit(1) }
    const number = Number(line.slice(0, 5))
    const count = Number(line.slice(5, 8))
    const body = line.slice(8).replace(/\s+$/, '')
    if (!Number.isInteger(number) || !Number.isInteger(count) || body.length !== count * 2) {
        console.error(`ASCII ${code}: glyph ${number} says ${count} pairs, has ${body.length / 2}`)
        process.exit(1)
    }
    glyphs.push({ code, number, body })
}

const out = `// GENERATED by scripts/laser/hershey-to-module.mjs from rowmans.jhf — do not edit by hand.
// Hershey Roman Simplex, ASCII ${FIRST}-${LAST} (${glyphs.length} glyphs), for Laser Text (laser.text).
//
// Source: npm \`hershey\` 2.1.7, font/jhf/rowmans.jhf, sha256 ${sha}, fetched 2026-10-20.
// Each entry is the glyph's .jhf body: pairs of characters, coordinate = code - 'R' (y runs down);
// the first pair is the left and right bounds; " R" lifts the pen.
//
// The acknowledgements the original distribution's notice requires to travel with the font data:
//   - The Hershey Fonts were originally created by Dr. A. V. Hershey while working at the U. S.
//     National Bureau of Standards.
//   - The format of the Font data in this distribution was originally created by
//       James Hurt
//       Cognition, Inc.
//       900 Technology Park Drive
//       Billerica, MA 01821
//       (mit-eddie!ci-dandelion!hurt)
// The notice also says the data may be converted into any format EXCEPT the one the U.S. NTIS distributes
// ("xxx yyy:" per point); this file is not in that format.

export const HERSHEY_ACKNOWLEDGEMENT = 'The Hershey Fonts were originally created by Dr. A. V. Hershey while working at the U. S. National Bureau of Standards. The format of the Font data in this distribution was originally created by James Hurt, Cognition, Inc., 900 Technology Park Drive, Billerica, MA 01821 (mit-eddie!ci-dandelion!hurt).'
export const HERSHEY_SOURCE = Object.freeze({ font: 'Roman Simplex (rowmans)', package: 'hershey@2.1.7', file: 'font/jhf/rowmans.jhf', sha256: '${sha}' })
export const FIRST_CODE = ${FIRST}
export const LAST_CODE = ${LAST}
// [Hershey glyph number, .jhf body], index = char code - ${FIRST}.
export const GLYPHS = Object.freeze([
${glyphs.map((g) => `    [${g.number}, ${JSON.stringify(g.body)}], // ${g.code === 92 ? 'backslash' : JSON.stringify(String.fromCharCode(g.code)).slice(1, -1)}`).join('\n')}
])
`
const target = path.join(root, 'src/project/nodes/laser.text/hersheyRomanSimplex.js')
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(target, out)
console.log(`wrote ${path.relative(root, target)}: ${glyphs.length} glyphs, source sha256 ${sha}`)
