// @vitest-environment node
// Audit 2026-10-21, G01/G02/G04/G06. nginx is not installed in CI, so this pins
// the config's shape: every page goes to serverXR's page route for EVERY user
// agent, every proxy to serverXR carries the public host (or the head goes out
// with relative or internal URLs — /wcc did), and the sitemap is the generated
// one, not a static file.
import { existsSync, readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const conf = readFileSync(path.join(root, 'nginx.conf'), 'utf8')
const code = conf.split('\n').filter((l) => !/^\s*#/.test(l)).join('\n')

// The body of `location <selector> { … }`, one level of braces deep.
const block = (selector) => {
  const start = code.indexOf(`location ${selector} {`)
  if (start < 0) return null
  return code.slice(start, code.indexOf('\n    }', start))
}

describe('nginx.conf: the page route', () => {
  it('no user-agent allowlist decides who gets a real head', () => {
    expect(code).not.toMatch(/\$http_user_agent/)
    expect(code).not.toMatch(/\/serverXR\/og/)
  })

  it('every non-file path, and the bare /, falls through to @page', () => {
    expect(block('/')).toMatch(/try_files \$uri \$uri\/index\.html @page;/)
    expect(block('= /')).toMatch(/try_files \S+ @page;/)
  })

  it('the shell serverXR fetches can never fall through to @page (a request loop)', () => {
    expect(block('= /index.html')).toMatch(/try_files \$uri =404;/)
  })

  it('@page passes serverXR the status (404 included) and falls back to the static shell only on failure', () => {
    const page = block('@page')
    expect(page).toMatch(/proxy_pass http:\/\/server:4000\/serverXR\/page\$uri;/)
    expect(page).toMatch(/proxy_intercept_errors on;/)
    expect(page).toMatch(/error_page 502 503 504 = @shell;/)
    expect(page).not.toMatch(/error_page[^;]*\b404\b/)
    expect(block('@shell')).toMatch(/try_files \/index\.html =404;/)
  })

  it('every proxy to serverXR that builds a head or a sitemap carries the public host', () => {
    for (const selector of ['@page', '= /sitemap.xml']) {
      const b = block(selector)
      expect(b, selector).toMatch(/proxy_set_header Host \$host;/)
      expect(b, selector).toMatch(/proxy_set_header X-Forwarded-Host \$host;/)
      expect(b, selector).toMatch(/proxy_set_header X-Forwarded-Proto \$dii_proto;/)
    }
  })

  it('/sitemap.xml is generated by serverXR, and no static copy is left to drift', () => {
    expect(block('= /sitemap.xml')).toMatch(/proxy_pass http:\/\/server:4000\/serverXR\/sitemap\.xml;/)
    expect(existsSync(path.join(root, 'public/sitemap.xml'))).toBe(false)
  })

  it('the page and the fallback shell are never cached long and keep the dev tier out of search', () => {
    for (const selector of ['@page', '@shell']) {
      expect(block(selector), selector).toMatch(/add_header Cache-Control "no-cache" always;/)
      expect(block(selector), selector).toMatch(/add_header X-Robots-Tag \$dii_noindex always;/)
    }
  })
})

describe('docker-compose.yml: the server can reach the shell', () => {
  const compose = readFileSync(path.join(root, 'docker-compose.yml'), 'utf8')
  it('SHELL_URL defaults to the client container\'s own index.html', () => {
    expect(compose).toMatch(/SHELL_URL: \$\{SHELL_URL:-http:\/\/client:8080\/index\.html\}/)
  })
})
